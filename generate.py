import torch
import torch.nn.functional as F


@torch.no_grad()
def generate(model, idx, max_new_tokens, temperature=1.0, top_k=None):
    # idx: [B, T] token ids; returns [B, T + max_new_tokens]
    was_training = model.training
    model.eval()

    block_size = model.config.block_size

    for _ in range(max_new_tokens):
        # The model only sees the last block_size tokens.
        idx_cond = idx[:, -block_size:]

        logits, _ = model(idx_cond)
        logits = logits[:, -1, :] / temperature  # [B, vocab]

        if top_k is not None:
            k = min(top_k, logits.size(-1))
            kth = torch.topk(logits, k).values[:, -1, None]
            logits = logits.masked_fill(logits < kth, float("-inf"))

        probs = F.softmax(logits, dim=-1)
        next_token = torch.multinomial(probs, num_samples=1)  # [B, 1]

        idx = torch.cat([idx, next_token], dim=1)

    model.train(was_training)
    return idx

import argparse

import torch
import torch.nn.functional as F

from config import GPTConfig
from model.gpt import GPT


@torch.no_grad()
def generate(
    model,
    idx,
    max_new_tokens=200,
    temperature=0.8,
    top_k=40,
):
    if temperature <= 0:
        raise ValueError("temperature must be positive")

    model.eval()

    for _ in range(max_new_tokens):

        # Keep only the last block_size tokens.
        idx_cond = idx[:, -model.config.block_size:]

        # Forward pass
        logits, _ = model(idx_cond)

        # Select logits from the final position
        logits = logits[:, -1, :]

        # Apply temperature
        logits = logits / temperature

        # Optional top-k filtering
        if top_k is not None:
            k = min(top_k, logits.size(-1))

            if k < 1:
                raise ValueError("top_k must be positive")

            values, _ = torch.topk(logits, k)

            threshold = values[:, -1].unsqueeze(-1)

            logits = logits.masked_fill(
                logits < threshold,
                float("-inf")
            )

        # Convert logits to probabilities
        probs = F.softmax(logits, dim=-1)

        # Sample one new token
        next_token = torch.multinomial(
            probs,
            num_samples=1
        )

        # Append the sampled token
        idx = torch.cat(
            [idx, next_token],
            dim=1
        )

    return idx


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--prompt",
        type=str,
        default="def "
    )

    parser.add_argument(
        "--max-new-tokens",
        type=int,
        default=200
    )

    parser.add_argument(
        "--temperature",
        type=float,
        default=0.8
    )

    parser.add_argument(
        "--top-k",
        type=int,
        default=40
    )

    parser.add_argument(
        "--checkpoint",
        type=str,
        default="checkpoints/tiny_gpt_best.pt"
    )

    args = parser.parse_args()

    device = (
        "cuda"
        if torch.cuda.is_available()
        else "cpu"
    )

    checkpoint = torch.load(
        args.checkpoint,
        map_location=device,
        weights_only=True
    )

    config = GPTConfig(**checkpoint["config"])

    model = GPT(config).to(device)

    model.load_state_dict(
        checkpoint["model_state_dict"]
    )

    # Convert prompt text into UTF-8 byte IDs.
    prompt_bytes = args.prompt.encode("utf-8")

    if not prompt_bytes:
        raise ValueError("Prompt cannot be empty")

    idx = torch.tensor(
        list(prompt_bytes),
        dtype=torch.long,
        device=device
    ).unsqueeze(0)

    output = generate(
        model,
        idx,
        max_new_tokens=args.max_new_tokens,
        temperature=args.temperature,
        top_k=args.top_k
    )

    # Convert generated byte IDs back to text.
    output_bytes = bytes(output[0].tolist())

    print(
        output_bytes.decode(
            "utf-8",
            errors="replace"
        )
    )


if __name__ == "__main__":
    main()
